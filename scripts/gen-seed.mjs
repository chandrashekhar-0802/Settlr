// Regenerates supabase/seed.sql from src/lib/demo-data.ts: node scripts/gen-seed.mjs
// Every row is is_demo = true and verified = false.
import { createJiti } from "jiti";
import { writeFileSync } from "node:fs";

const jiti = createJiti(import.meta.url);
const { DEMO_LISTINGS } = await jiti.import("../src/lib/demo-data.ts");
const q = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const CORE = new Set(["id", "category", "kind", "name", "locality", "city", "lat", "lng", "description", "monthly", "oneTime", "deposit", "priceNote", "amenities", "verified", "isDemo"]);

const rows = DEMO_LISTINGS.map((l) => {
  const attrs = Object.fromEntries(Object.entries(l).filter(([k]) => !CORE.has(k)));
  return `(${[q(l.id), q(l.category), q(l.kind), q(l.name), q(l.locality), q(l.city), l.lat, l.lng, q(l.description), l.monthly, l.oneTime, l.deposit, q(l.priceNote), `array[${l.amenities.map(q).join(",")}]::text[]`, `${q(JSON.stringify(attrs))}::jsonb`, "false", "true", "true"].join(", ")})`;
});

writeFileSync(
  "supabase/seed.sql",
  `-- DEMO DATA ONLY (generated by scripts/gen-seed.mjs). Fictional providers, illustrative prices. Always shown with a DEMO badge.
insert into public.listings (id, category, kind, name, locality, city, lat, lng, description, monthly, one_time, deposit, price_note, amenities, attrs, verified, is_demo, published) values
${rows.join(",\n")}
on conflict (id) do nothing;
`,
);
console.log(`wrote supabase/seed.sql (${rows.length} demo listings)`);
